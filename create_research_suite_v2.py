    "def calc_mse(model, dataloader, model_type):\n",
    "    model.eval()\n",
    "    total = 0\n",
    "    count = 0\n",
    "    with torch.no_grad():\n",
    "        for x, _ in tqdm(dataloader, desc=\"MSE\"):\n",
    "            x = x.to(device)\n",
    "            if model_type == 'vae':\n",
    "                _, recon = model(x)\n",
    "            else:\n",
    "                out = model(x)\n",
    "                recon = out['x_rec']\n",
    "            total += nn.functional.mse_loss(recon, x).item()\n",
    "            count += 1\n",
    "    return total / count\n",
    "\n",
    "def visualize_latent_interp(base_model, dataloader, model_type):\n",
    "    base_model.eval()\n",
    "    x, _ = next(iter(dataloader))\n",
    "    x = x.to(device)\n",
    "    \n",
    "    with torch.no_grad():\n",
    "        if model_type == 'vae':\n",
    "            z, _ = base_model(x)\n",
    "            z1, z2 = z[0:1], z[1:2]\n",
    "            # VAE decode simple\n",
    "            decode_fn = lambda z: base_model.decoder(z)\n",
    "        else:\n",
    "            # NVAE: extracting z_g (global)\n",
    "            # We interpolate z_g, but what about z_fine?\n",
    "            # We can fix z_fine from z1, or sample new z_fine.\n",
    "            # Ideally we interpolate z_g and let prior p(z_f|z_g) sample z_f.\n",
    "            mu_g, _, _, _, _, _ = base_model.encoder(x)\n",
    "            z1, z2 = mu_g[0:1], mu_g[1:2]\n",
    "            decode_fn = lambda z: base_model.decoder(z, z_fine=None)[0]\n",
    "\n",
    "    alphas = torch.linspace(0, 1, 10).to(device)\n",
    "    images = []\n",
    "    for a in alphas:\n",
    "        z_interp = (1-a)*z1 + a*z2\n",
    "        recon = decode_fn(z_interp)\n",
    "        images.append(recon.cpu().squeeze())\n",
    "        \n",
    "    fig, axs = plt.subplots(1, 10, figsize=(20, 2))\n",
    "    for i in range(10):\n",
    "        img = images[i].permute(1, 2, 0).detach().numpy() * 0.5 + 0.5\n",
    "        axs[i].imshow(np.clip(img, 0, 1))\n",
    "        axs[i].axis('off')\n",
    "    plt.show()\n",
    "\n",
