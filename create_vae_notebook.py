    "def train_vae(dataloader, z_dim=64, n_epochs=50, lr=1e-3, print_every=100, save_path=\"checkpoints/best_vae.pth\"):\n",
    "    os.makedirs(os.path.dirname(save_path), exist_ok=True)\n",
    "    \n",
    "    # Standard VAE\n",
    "    model = Model(3, 32, 3, 128, z_dim, 32, 32).to(device)\n",
    "    optimizer = torch.optim.Adam(model.parameters(), lr=lr)\n",
    "    \n",
    "    best_loss = float('inf')\n",
    "    \n",
    "    for epoch in range(n_epochs):\n",
    "        model.train()\n",
    "        epoch_loss = 0\n",
    "        steps = 0\n",
    "        \n",
    "        for images, _ in dataloader:\n",
    "            images = images.to(device)\n",
    "            \n",
    "            # Forward\n",
    "            # Note: The Model class in train_utils presumably returns (z, recon)\n",
    "            # and might compute KL internally or we need to do it.\n",
    "            # Checking previous context, it seems Model wraps encoder/decoder.\n",
    "            # We'll assume standard VAE loss: Recon + KL\n",
    "            \n",
    "            mu, logvar = model.encoder(images)\n",
    "            z = model.reparameterize(mu, logvar)\n",
    "            recon = model.decoder(z)\n",
    "            \n",
    "            # Reconstruction Loss\n",
    "            recon_loss = F.mse_loss(recon, images, reduction='sum') / images.shape[0]\n",
    "            \n",
    "            # KL Divergence\n",
    "            # -0.5 * sum(1 + log(sigma^2) - mu^2 - sigma^2)\n",
    "            kl_loss = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) / images.shape[0]\n",
    "            \n",
    "            loss = recon_loss + 0.00025 * kl_loss # Weighting KL to avoid collapse\n",
    "            \n",
    "            optimizer.zero_grad()\n",
    "            loss.backward()\n",
    "            optimizer.step()\n",
    "            \n",
    "            epoch_loss += loss.item()\n",
    "            steps += 1\n",
    "            \n",
    "            if steps % print_every == 0:\n",
    "                print(f\"Epoch [{epoch+1}/{n_epochs}] Step [{steps}] Loss: {loss.item():.4f} (Recon: {recon_loss.item():.4f}, KL: {kl_loss.item():.4f})\")\n",
    "        \n",
    "        avg_loss = epoch_loss / steps\n",
    "        print(f\"====> Epoch: {epoch+1} Average Loss: {avg_loss:.4f}\")\n",
    "        \n",
    "        # Save Best Model\n",
    "        if avg_loss < best_loss:\n",
    "            print(f\"New best loss! Saving to {save_path}\")\n",
    "            best_loss = avg_loss\n",
    "            torch.save(model.state_dict(), save_path)\n",
