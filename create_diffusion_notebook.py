    "def train_latent_diffusion(dataloader, vae_path, z_dim=64, n_epochs=50, lr=1e-4, save_path=\"checkpoints/best_diffusion.pth\"):\n",
    "    os.makedirs(os.path.dirname(save_path), exist_ok=True)\n",
    "    \n",
    "    # 1. Load Pretrained VAE\n",
    "    vae = Model(3, 32, 3, 128, z_dim, 32, 32).to(device)\n",
    "    vae.load_state_dict(torch.load(vae_path, map_location=device))\n",
    "    vae.eval()\n",
    "    # Freeze VAE\n",
    "    for param in vae.parameters():\n",
    "        param.requires_grad = False\n",
    "        \n",
    "    print(\"Loaded VAE from\", vae_path)\n",
    "\n",
    "    # 2. Setup Diffusion Model\n",
    "    time_dim = 64\n",
    "    denoiser = ResidualDenoiser(\n",
    "        input_dim=z_dim + time_dim,\n",
    "        model_dim=1024,\n",
    "        output_dim=z_dim,\n",
    "        n_blocks=8\n",
    "    )\n",
    "    \n",
    "    ddpm = DDPM(\n",
    "        network=denoiser,\n",
    "        z_dim=z_dim,\n",
    "        n_steps=1000,\n",
    "        device=device\n",
    "    ).to(device)\n",
    "    \n",
    "    optimizer = torch.optim.Adam(ddpm.parameters(), lr=lr)\n",
    "    \n",
    "    best_loss = float('inf')\n",
    "\n",
    "    for epoch in range(n_epochs):\n",
    "        ddpm.train()\n",
    "        epoch_loss = 0\n",
    "        steps = 0\n",
    "        \n",
    "        for images, _ in dataloader:\n",
    "            images = images.to(device)\n",
    "            \n",
    "            # Extract Latents with VAE Encoder\n",
    "            with torch.no_grad():\n",
    "                mu, logvar = vae.encoder(images)\n",
    "                # Determine what z to train on.\n",
    "                # Option A: Train on mu (deterministic)\n",
    "                # Option B: Train on sampled z (stochastic)\n",
    "                # Standard LDM often uses the posterior mean or samples.\n",
    "                # Given MMD-VAE often has small variance, mu is fine.\n",
    "                # But for robustness, let's use reparameterized z.\n",
    "                z = vae.reparameterize(mu, logvar)\n",
    "            \n",
    "            # Train Diffusion on z\n",
    "            # We assume z has been regularized to be somewhat standard normal by VAE.\n",
    "            loss = ddpm.compute_loss(z)\n",
    "            \n",
    "            optimizer.zero_grad()\n",
    "            loss.backward()\n",
    "            optimizer.step()\n",
    "            \n",
    "            epoch_loss += loss.item()\n",
    "            steps += 1\n",
    "            \n",
    "        avg_loss = epoch_loss / steps\n",
    "        print(f\"Epoch: {epoch+1} Diffusion Loss: {avg_loss:.5f}\")\n",
    "        \n",
    "        if avg_loss < best_loss:\n",
    "            best_loss = avg_loss\n",
    "            torch.save(ddpm.state_dict(), save_path)\n",
    "            print(f\"Saved diffusion model to {save_path}\")\n",
    "            \n",
    "        # Visualize Samples\n",
    "        if (epoch + 1) % 5 == 0:\n",
    "             with torch.no_grad():\n",
    "                ddpm.eval()\n",
    "                n_vis = 8\n",
    "                z_gen = ddpm.sample(n_vis)\n",
    "                x_gen = vae.decoder(z_gen)\n",
    "                x_gen = x_gen.cpu().permute(0, 2, 3, 1).numpy() * 0.5 + 0.5\n",
    "                \n",
    "                fig, axs = plt.subplots(1, n_vis, figsize=(n_vis*2, 2))\n",
    "                for i in range(n_vis):\n",
    "                    axs[i].imshow(np.clip(x_gen[i], 0, 1))\n",
    "                    axs[i].axis('off')\n",
    "                plt.show()\n",
    "                \n",
    "    return ddpm\n"
