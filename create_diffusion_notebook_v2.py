    "def train_latent_diffusion(model_type, dataset_name, z_dim=64, n_epochs=50):\n",
    "    # 1. Load Base Model\n",
    "    base_ckpt = f\"checkpoints/best_{model_type}_{dataset_name}.pth\"\n",
    "    diff_ckpt = f\"checkpoints/best_diffusion_{model_type}_{dataset_name}.pth\"\n",
    "    \n",
    "    if not os.path.exists(base_ckpt):\n",
    "        print(f\"Error: Base model {base_ckpt} not found. Train Stage 1 first.\")\n",
    "        return\n",
    "        \n",
    "    IMG_RES = 32\n",
    "    if model_type == 'vae':\n",
    "        base_model = Model(3, 32, 3, 128, z_dim, 32, 32).to(device)\n",
    "    else:\n",
    "        base_model = NVAE(z_dim=z_dim, input_res=IMG_RES).to(device)\n",
    "        \n",
    "    base_model.load_state_dict(torch.load(base_ckpt, map_location=device))\n",
    "    base_model.eval()\n",
    "    for p in base_model.parameters(): p.requires_grad = False\n",
    "    print(f\"Loaded frozen {model_type} from {base_ckpt}\")\n",
    "\n",
    "    # 2. Setup Diffusion\n",
    "    # Standard config: 8 blocks, model_dim=1024 (can scale down for speed)\n",
    "    denoiser = ResidualDenoiser(\n",
    "        input_dim=z_dim + 64, # z + time_emb\n",
    "        model_dim=512,        # Scaled down to 512 for faster training demo\n",
    "        output_dim=z_dim,\n",
    "        n_blocks=6\n",
    "    )\n",
    "    ddpm = DDPM(denoiser, z_dim=z_dim, n_steps=1000, device=device).to(device)\n",
    "    optimizer = torch.optim.Adam(ddpm.parameters(), lr=2e-4)\n",
    "\n",
    "    # 3. Data Loop\n",
    "    dataloader = get_dataloader(dataset_name, batch_size=128, image_size=IMG_RES)\n",
    "    best_loss = float('inf')\n",
    "    \n",
    "    print(\"Starting Diffusion Training...\")\n",
    "    for epoch in range(n_epochs):\n",
    "        ddpm.train()\n",
    "        total_loss = 0\n",
    "        steps = 0\n",
    "        \n",
    "        for x, _ in dataloader:\n",
    "            x = x.to(device)\n",
    "            \n",
    "            with torch.no_grad():\n",
    "                if model_type == 'vae':\n",
    "                    mu, logvar = base_model.encoder(x)\n",
    "                    z = base_model.reparameterize(mu, logvar)\n",
    "                else: # nvae\n",
    "                    # NVAE forward returns mu_g, log_g etc. or we call encoder directly.\n",
    "                    # Encoder returns: mu_g, log_g, mu_f, log_f, ...\n",
    "                    mu_g, log_g, _, _, _, _ = base_model.encoder(x)\n",
    "                    std_g = torch.exp(0.5 * log_g)\n",
    "                    z = mu_g + torch.randn_like(mu_g) * std_g\n",
    "            \n",
    "            # Train DDPM on z\n",
    "            loss = ddpm.compute_loss(z)\n",
    "            \n",
    "            optimizer.zero_grad()\n",
    "            loss.backward()\n",
    "            optimizer.step()\n",
    "            total_loss += loss.item()\n",
    "            steps += 1\n",
    "            \n",
    "        avg_loss = total_loss / steps\n",
    "        print(f\"Epoch {epoch+1}: Loss {avg_loss:.5f}\")\n",
    "        \n",
    "        if avg_loss < best_loss:\n",
    "            best_loss = avg_loss\n",
    "            torch.save(ddpm.state_dict(), diff_ckpt)\n",
    "            print(\"Saved checkpoint.\")\n",
    "            \n",
    "        # Visualize\n",
    "        if (epoch+1) % 5 == 0:\n",
    "             with torch.no_grad():\n",
    "                z_gen = ddpm.sample(8)\n",
    "                if model_type == 'vae':\n",
    "                     x_gen = base_model.decoder(z_gen)\n",
    "                else:\n",
    "                     # NVAE decode: needs z_global, and will sample z_fine from prior\n",
    "                     x_gen, _, _ = base_model.decoder(z_gen, z_fine=None)\n",
    "                \n",
    "                x_gen = x_gen.cpu().permute(0, 2, 3, 1).numpy() * 0.5 + 0.5\n",
    "                fig, axs = plt.subplots(1, 8, figsize=(16, 2))\n",
    "                for i in range(8):\n",
    "                    axs[i].imshow(np.clip(x_gen[i], 0, 1))\n",
    "                    axs[i].axis('off')\n",
    "                plt.show()\n",
    "\n",
    "    return ddpm"
